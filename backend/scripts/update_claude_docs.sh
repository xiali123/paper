#!/bin/bash

# =============================================================================
# CLAUDE.md 自动更新脚本
# =============================================================================
#
# 用途: 完成复杂任务后，自动更新CLAUDE.md和相关文档
#
# 使用方法:
#   bash scripts/update_claude_docs.sh <问题类型> <标题>
#
# 示例:
#   bash scripts/update_claude_docs.sh solution "Gumbo HTML解析器集成"
#   bash scripts/update_claude_docs.sh integration "第三方库动态DLL编译"
#   bash scripts/update_claude_docs.sh decision "采用动态DLL架构"
#
# =============================================================================

set -e

DOC_TYPE=${1:-"solution"}
TITLE=${2:-"未命名更新"}
DATE=$(date +%Y-%m-%d)
TIMESTAMP=$(date +%Y%m%d_%H%M%S)

echo "🔄 CLAUDE.md 自动更新"
echo "====================================="
echo "类型: $DOC_TYPE"
echo "标题: $TITLE"
echo "日期: $DATE"
echo ""

# 创建报告文件
REPORT_FILE="reports/${TITLE// /_}_${TIMESTAMP}.md"
REPORT_DIR=$(dirname "$REPORT_FILE")

# 确保reports目录存在
mkdir -p "$REPORT_DIR"

echo "📝 创建报告文件: $REPORT_FILE"

# 根据类型生成模板
case $DOC_TYPE in
    "solution"|"problem")
        cat > "$REPORT_FILE" << EOF
# ${TITLE} - 问题解决方案

**类型**: 问题解决
**日期**: ${DATE}
**状态**: ✅ 已解决

---

## 问题描述

**症状**:
<!-- 描述遇到的具体错误或问题 -->

**根本原因**:
<!-- 深入分析问题的根本原因 -->

---

## 解决方案

### 实施步骤

1. <!-- 步骤1 -->
2. <!-- 步骤2 -->
3. <!-- 步骤3 -->

### 关键代码

\`\`\`cpp
// 修复前（错误）
// ❌ 错误代码

// 修复后（正确）
// ✅ 正确代码
\`\`\`

---

## 经验总结

### 关键经验

1. **经验1**: <!-- 描述 -->
2. **经验2**: <!-- 描述 -->

### 预防措施

- ✅ <!-- 如何避免再次出现 -->

### 相关文件

- **修改的文件**:
  - <!-- 文件1 -->
  - <!-- 文件2 -->

- **新增文件**:
  - <!-- 文件3 -->

### 耗时统计

- 分析问题: <!-- 时间 -->
- 解决问题: <!-- 时间 -->
- 编写文档: <!-- 时间 -->
- **总计**: <!-- 总时间 -->

---

## 应用场景

这个解决方案适用于：
- ✅ <!-- 场景1 -->
- ✅ <!-- 场景2 -->

---

EOF
        ;;

    "integration")
        cat > "$REPORT_FILE" << EOF
# ${TITLE} - 技术集成报告

**类型**: 技术集成
**日期**: ${DATE}
**状态**: ✅ 已完成

---

## 技术概述

**技术名称**: <!-- 技术名称 -->
**版本**: <!-- 版本 -->
**用途**: <!-- 技术的作用 -->
**官方文档**: <!-- 文档链接 -->

---

## 集成过程

### 难度评估

- **集成难度**: [简单/中等/困难]
- **预计时间**: <!-- 预计 -->
- **实际时间**: <!-- 实际 -->

### 集成步骤

1. <!-- 步骤1 -->
2. <!-- 步骤2 -->
3. <!-- 步骤3 -->

---

## 遇到的坑

### 问题1: <!-- 问题描述 -->

**症状**:
<!-- 错误信息 -->

**解决方案**:
<!-- 如何解决 -->

### 问题2: <!-- 问题描述 -->

**症状**:
<!-- 错误信息 -->

**解决方案**:
<!-- 如何解决 -->

---

## 最佳实践

### DO ✅

1. **实践1**: <!-- 描述 -->
2. **实践2**: <!-- 描述 -->

### DON'T ❌

1. **错误1**: <!-- 描述 -->
2. **错误2**: <!-- 描述 -->

---

## 代码示例

### 基本用法

\`\`\`cpp
// 示例代码
#include "${TECH_LIBRARY}.h"

int main() {
    // 使用技术
    ${TECH_LIBRARY}_function();
    return 0;
}
\`\`\`

### CMake配置

\`\`\`cmake
# CMakeLists.txt
add_third_party_library(${TECH_LIBRARY})
\`\`\`

---

## 验证方法

### 编译验证

\`\`\`bash
cd backend/build
cmake .. -DCMAKE_BUILD_TYPE=Release
cmake --build . --config Release
\`\`\`

### 功能验证

\`\`\`bash
# 测试命令
<!-- 测试步骤 -->
\`\`\`

---

## 相关文档

- **官方文档**: <!-- 链接 -->
- **API文档**: <!-- 链接 -->
- **示例代码**: <!-- 位置 -->
- **相关报告**: <!-- 链接到其他报告 -->

---

EOF
        ;;

    "decision"|"adr")
        cat > "$REPORT_FILE" << EOF
# ADR: ${TITLE}

**类型**: 架构决策记录（ADR）
**状态**: 已接受
**日期**: ${DATE}
**决策编号**: ADR-$(date +%Y%m%d)

---

## 背景

**问题**: <!-- 为什么要做这个决策 -->
**驱动力**: <!-- 什么推动了这次决策 -->

---

## 决策

**我们决定**: <!-- 决策内容 -->

---

## 理由

### 优点

1. **优点1**: <!-- 描述 -->
2. **优点2**: <!-- 描述 -->

### 缺点

1. **缺点1**: <!-- 描述 -->
2. **缺点2**: <!-- 描述 -->

---

## 后果

### 正面影响

- ✅ <!-- 影响1 -->
- ✅ <!-- 影响2 -->

### 负面影响

- ⚠️ <!-- 影响1 -->
- ⚠️ <!-- 影响2 -->

**缓解措施**:
<!-- 如何缓解负面影响 -->

---

## 替代方案

### 方案1: <!-- 方案名称 -->

**描述**: <!-- 描述 -->

**为什么未选择**:
<!-- 原因 -->

### 方案2: <!-- 方案名称 -->

**描述**: <!-- 描述 -->

**为什么未选择**:
<!-- 原因 -->

---

## 实施

### 阶段1: <!-- 阶段1 -->

- [ ] <!-- 任务1 -->
- [ ] <!-- 任务2 -->

### 阶段2: <!-- 阶段2 -->

- [ ] <!-- 任务1 -->
- [ ] <!-- 任务2 -->

---

## 相关决策

- **相关ADR**: <!-- 链接到相关ADR -->
- **影响范围**: <!-- 影响的模块/组件 -->

---

EOF
        ;;

    *)
        cat > "$REPORT_FILE" << EOF
# ${TITLE} - 文档更新

**类型**: 通用更新
**日期**: ${DATE}

---

## 更新内容

<!-- 在这里描述更新内容 -->

---

## 更新原因

<!-- 为什么需要这次更新 -->

---

## 变更摘要

- [ ] 新增内容
- [ ] 修改内容
- [ ] 删除内容

---

## 相关文件

- <!-- 文件列表 -->

---
EOF
        ;;
esac

echo "✅ 报告文件创建成功: $REPORT_FILE"
echo ""

# 询问是否需要编辑报告
echo "📝 是否立即编辑报告？"
echo "   [Y]es - 立即编辑报告"
echo "   [N]o - 稍后手动编辑"
echo "   [A]bort - 取消"
echo ""
read -p "选择: " choice

case $choice in
    y|Y|yes|YES)
        ${EDITOR:-nano} "$REPORT_FILE"
        ;;
    n|N|no|NO)
        echo "⏸️  跳过编辑，稍后手动编辑"
        ;;
    *)
        echo "❌ 取消操作"
        rm "$REPORT_FILE"
        exit 0
        ;;
esac

echo ""
echo "📋 下一步:"
echo ""
echo "1. 编辑报告文件，补充具体内容:"
echo "   vim $REPORT_FILE"
echo ""
echo "2. 将经验提取到CLAUDE.md:"
echo "   # 根据报告内容，在CLAUDE.md中添加相关章节"
echo ""
echo "3. 提交更新:"
echo "   git add CLAUDE.md $REPORT_FILE"
echo "   git commit -m \"docs: 更新CLAUDE.md - ${TITLE}\""
echo ""
